export function industriesFor(bcType) {
  if (!bcType) return [...new Map([...INDUSTRIES_STANDARD, ...INDUSTRIES_SELF_SERVICE].map((r) => [r[0], r])).values()];
  return SELF_SERVICE_TYPES.has(bcType) ? INDUSTRIES_SELF_SERVICE : INDUSTRIES_STANDARD;
}

export const isIndustryFor = (id, bcType) => industriesFor(bcType).some(([value]) => value === id);
